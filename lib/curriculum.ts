/**
 * Gifted (מחוננים) reasoning track: original items in the style of Israeli
 * gifted-screening prep. The source of truth here is the *logic* - every item
 * must have exactly one defensible answer at the child's age.
 */
function giftedGuidance(grade: string): string {
  const range = grade === 'grade_3'
    ? 'טווח מספרים קטן וסביר לכיתה ג׳ (עד ~100 בסדרות), מילים מוכרות מעולם הילד'
    : 'טווח מספרים סביר לכיתה ה׳, אוצר מילים עשיר יותר אך מוכר';
  return `מסלול מחוננים - חשיבה והיגיון (בסגנון מבחני איתור). ${range}.
עקרונות חובה:
- לכל פריט תשובה אחת נכונה שאפשר להגן עליה בהיגיון, בלי עמימות ובלי "גם וגם".
- אנלוגיה מילולית: היחס בין הזוג הראשון זהה לחלוטין ליחס בזוג הנכון (למשל גור:כלב כמו X:חתול -> גור חתול). רק אפשרות אחת שומרת על אותו יחס בדיוק.
- סדרת מספרים: חוק אחד עקבי (למשל +3 בכל פעם, או כפול 2) שמסביר את כל האיברים; התשובה היא האיבר הבא לפי החוק.
- היוצא דופן: בדיוק אחד מהפריטים לא שייך לקבוצה מסיבה ברורה ויחידה; שלושת האחרים חולקים תכונה משותפת מובהקת.
- חשיבה לוגית: חידה קצרה עם הסקה ודאית ויחידה מהנתונים בלבד, בלי ידע חיצוני נדיר.
פסול: פריט שאפשר לפתור אותו ביותר מדרך אחת שמובילה לתשובות שונות, יחס אנלוגיה לא עקבי, סדרה עם יותר מחוק אפשרי, או "יוצא דופן" ששניים ממנו יכולים להיחשב חריגים.`;
}

export function curriculumGroundTruth(subject: string, grade: string): string {
  return CURRICULUM[subject]?.[grade] ?? '';
}

/**
 * Resolve the right ground-truth for any subject: school curriculum for core
 * subjects, the concept anchor for enrichment subjects, or the logic rules for
 * the gifted track. Returns '' when nothing applies (falls back to grade rules).
 */
export function groundTruthFor(subject: string, grade: string): string {
  const core = CURRICULUM[subject]?.[grade];
  if (core) return core;
  if (subject === 'gifted') return giftedGuidance(grade);
  return ENRICHMENT_GUIDANCE[subject] ?? '';
}
